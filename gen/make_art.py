# ---- The walk: six frames, made by moving each foot along a smooth path.
# Each leg goes from the hip to its foot; the foot slides back while it's on
# the ground, then lifts and swings forward. The far leg is a darker blue.
import math
def legs(phase):
    rows = [list("....CCCCCCCC....")] + [list("." * 16) for _ in range(10)]
    def leg(off, lift, col):
        hip = 7.0
        for r in range(1, 8 - lift):                 # rows 22.. down to the ankle
            t = r / 7.0
            x = hip + off * t
            for dx in (-1, 0, 1):
                c = int(math.floor(x + dx + 0.5))
                if 0 <= c < 16: rows[r][c] = col
        fy = 8 - lift                                # the boot
        fx = int(math.floor(hip + off + 0.5))
        for c in range(fx - 1, fx + 2):
            if 0 <= c < 16: rows[fy][c] = '5'
        for c in range(fx - 1, fx + 3):
            if 0 <= c < 16:
                rows[fy + 1][c] = '5'
                rows[fy + 2][c] = '5'
    def foot(i):
        p = 2 * math.pi * i / 6
        off = 5 * math.cos(p)
        swing = math.sin(p) < -0.1                   # moving forward: in the air
        return off, (2 if swing and abs(off) < 4 else 1 if swing else 0)
    near, far = foot(phase), foot(phase + 3)
    leg(far[0], far[1], 'D')                         # the far leg first,
    leg(near[0], near[1], 'C')                       # then the near one over it
    return ["".join(r) for r in rows]
