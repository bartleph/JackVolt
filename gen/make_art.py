# ---- Tiles, made with a little code so they stay tidy
def wall_bricks(mortar, face, light):
    rows=[]
    for y in range(16):
        r=""
        for x in range(16):
            row=y//4; off=(row%2)*4
            if y%4==3 or (x+off)%8==7: r+=mortar
            elif y%4==0 or (x+off)%8==0: r+=light
            else: r+=face
        rows.append(r)
    return rows
def plate(edge, face, rivet, light):
    rows=[]
    for y in range(16):
        r=""
        for x in range(16):
            if x==15 or y==15: r+=edge
            elif x==0 or y==0: r+=light
            elif (x,y) in ((2,2),(13,2),(2,13),(13,13)): r+=rivet
            else: r+=face
        rows.append(r)
    return rows
def girder(edge, face, hole):
    rows=[]
    for y in range(16):
        r=""
        for x in range(16):
            if y in (0,1,14,15): r+=edge
            elif (x+y)%8 in (0,1) and 3<=y<=12: r+=hole
            else: r+=face
        rows.append(r)
    return rows
def hazard():
    rows=[]
    for y in range(16):
        r=""
        for x in range(16):
            if y in (0,15): r+='5'
            elif y in (1,14): r+='6'
            else: r+= 'A' if ((x+y)//4)%2==0 else '0'
        rows.append(r)
    return rows
def ledge(top, face, under):
    rows=[top*16, face*16, face*16, under*16, under.join(['.']*1)*0+"".join(under if x%4==0 else '.' for x in range(16))]
    return rows+['.'*16]*11
def cracked(base, crack, light):
    rows=wall_bricks(crack, base, light)
    cr=[(3,5),(4,6),(5,6),(6,7),(10,9),(11,10),(11,11),(12,12),(8,2),(9,3)]
    rows=[list(r) for r in rows]
    for x,y in cr: rows[y][x]='0'
    return ["".join(r) for r in rows]
def tech(face, line, edge):
    rows=[]
    for y in range(16):
        r=""
        for x in range(16):
            if x==15 or y==15: r+='0'
            elif x==0 or y==0: r+=edge
            elif y==7 and 3<=x<=12: r+=line
            elif (x==3 or x==12) and 4<=y<=10: r+=line
            else: r+=face
        rows.append(r)
    return rows

